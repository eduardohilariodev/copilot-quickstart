// ─── YAML Formatter ─────────────────────────────────────────────────────────

export function formatYaml(obj, indent = 0) {
  const pad = " ".repeat(indent);
  let out = "";

  for (const [key, value] of Object.entries(obj)) {
    if (value === null || value === undefined) continue;

    if (Array.isArray(value)) {
      if (value.length === 0) {
        out += `${pad}${key}: []\n`;
      } else if (typeof value[0] === "object") {
        out += `${pad}${key}:\n`;
        for (const item of value) {
          const lines = formatYaml(item, indent + 4)
            .split("\n")
            .filter(Boolean);
          out += `${pad}  - ${lines[0].trim()}\n`;
          for (const line of lines.slice(1)) {
            out += `${pad}    ${line.trim()}\n`;
          }
        }
      } else {
        out += `${pad}${key}:\n`;
        for (const item of value) {
          out += `${pad}  - ${item.includes(" ") || item.includes("*") ? `"${item}"` : item}\n`;
        }
      }
    } else if (typeof value === "object") {
      out += `${pad}${key}:\n`;
      out += formatYaml(value, indent + 2);
    } else if (typeof value === "string" && (value.includes(" ") || value.includes("<"))) {
      out += `${pad}${key}: "${value}"\n`;
    } else {
      out += `${pad}${key}: ${value}\n`;
    }
  }

  return out;
}

// ─── File Generators ────────────────────────────────────────────────────────

export function generateProfileYaml(profile) {
  return (
    `# Repository Profile\n` +
    `# yaml-language-server: $schema=https://raw.githubusercontent.com/eduardohilariodev/copilot-quickstart/main/schemas/repo-profile.schema.json\n` +
    `# Generated by copilot-quickstart v2.0.0\n` +
    `# Review and fill in <placeholders> before running meta-skills\n\n` +
    formatYaml(profile)
  );
}

export function generateAgentsMd(profile) {
  const name = profile.name || "this-repo";
  const langs = profile.languages?.join(", ") || "not specified";
  const frameworks = profile.frameworks?.join(", ") || "none";
  const arch = profile.architecture || "monolith";
  const cmds = profile.build_commands || {};

  let md = `# AGENTS.md — ${name}\n\n`;
  md += `## Quick Reference\n\n`;
  md += `| Key | Value |\n|-----|-------|\n`;
  md += `| Languages | ${langs} |\n`;
  md += `| Frameworks | ${frameworks} |\n`;
  md += `| Architecture | ${arch} |\n`;
  md += `| Risk Level | ${profile.risk_level || "medium"} |\n\n`;

  md += `## Commands\n\n`;
  md += `| Action | Command |\n|--------|--------|\n`;
  if (cmds.install) md += `| Install | \`${cmds.install}\` |\n`;
  if (cmds.build) md += `| Build | \`${cmds.build}\` |\n`;
  if (cmds.test) md += `| Test | \`${cmds.test}\` |\n`;
  if (cmds.lint) md += `| Lint | \`${cmds.lint}\` |\n`;
  if (cmds.dev) md += `| Dev | \`${cmds.dev}\` |\n`;
  md += `\n`;

  md += `## Architecture\n\n`;
  md += `<!-- Fill in: describe key modules, boundaries, and data flow -->\n\n`;

  md += `## Code Conventions\n\n`;
  md += `- Follow existing patterns in the codebase\n`;
  md += `- ${profile.conventions?.naming || "Use consistent naming conventions"}\n`;
  md += `- ${profile.conventions?.testing_strategy || "Write tests for new features"}\n\n`;

  md += `## Protected Paths\n\n`;
  md += `Do NOT modify these without explicit approval:\n`;
  md += (profile.protected_paths || [".env*"]).map((p) => `- \`${p}\``).join("\n");
  md += `\n\n`;

  md += `## Agent Guidelines\n\n`;
  md += `- Read this file before making changes\n`;
  md += `- Run tests after every modification\n`;
  md += `- Keep commits small and focused\n`;
  md += `- Ask before architectural changes\n\n`;

  md += `## AI Maintenance\n\n`;
  md += `Run periodically to keep AI config healthy:\n`;
  md += `- Weekly: \`health-dashboard\`\n`;
  md += `- Monthly: \`audit-skills\`, \`detect-drift\`\n`;
  md += `- Quarterly: \`prune-skills\`, \`check-compatibility\`\n`;

  return md;
}

export function generateInstructions(profile) {
  const langs = profile.languages?.join(", ") || "this project";
  const frameworks = profile.frameworks?.join(", ");

  let md = `# Copilot Instructions\n\n`;
  md += `## Project Context\n\n`;
  md += `This is a ${profile.architecture || "monolith"} project using ${langs}${frameworks ? ` with ${frameworks}` : ""}.\n\n`;

  md += `## Code Style\n\n`;
  md += `- Follow existing patterns in the codebase\n`;
  md += `- ${profile.conventions?.naming || "Use consistent naming conventions"}\n`;
  md += `- Write clear, self-documenting code\n\n`;

  md += `## Testing\n\n`;
  md += `- ${profile.conventions?.testing_strategy || "Write tests for new features and bug fixes"}\n`;
  if (profile.build_commands?.test) {
    md += `- Run tests: \`${profile.build_commands.test}\`\n`;
  }
  md += `\n`;

  md += `## Safety\n\n`;
  md += `- Never modify files matching: ${(profile.protected_paths || [".env*"]).join(", ")}\n`;
  md += `- Never commit secrets or credentials\n`;
  md += `- Always verify changes compile/pass before committing\n\n`;

  md += `## When Unsure\n\n`;
  md += `- Check AGENTS.md for architecture guidance\n`;
  md += `- Look at existing similar code for patterns\n`;
  md += `- Ask the developer rather than guessing\n`;

  return md;
}

