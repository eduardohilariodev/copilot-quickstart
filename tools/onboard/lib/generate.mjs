// ─── Staging Orchestrator ───────────────────────────────────────────────────

/**
 * Write all planned artifacts to the staging directory.
 * @returns {{ written: string[], skipped: string[] }}
 */
export function stageArtifacts(target, artifacts, profile, scan) {
  const stagingDir = join(target, STAGING_DIR_NAME);
  const written = [];
  const skipped = [];

  for (const artifact of artifacts) {
    if (artifact.action === "skip") {
      skipped.push(artifact.label);
      continue;
    }

    const destPath = join(stagingDir, artifact.stagePath);

    // Ensure directory exists
    mkdirSync(dirname(destPath), { recursive: true });

    // Generate content based on artifact type
    switch (artifact.id) {
      case "repo-profile":
        writeFileSync(destPath, generateProfileYaml(profile), "utf8");
        break;

      case "agents-md":
        writeFileSync(destPath, generateAgentsMd(profile), "utf8");
        break;

      case "copilot-instructions":
        writeFileSync(destPath, generateInstructions(profile), "utf8");
        break;

      case "vscode-settings":
        writeFileSync(destPath, generateVscodeSettings(), "utf8");
        break;

      case "starter-skills":
        stageSkills(destPath);
        break;

      default:
        // Path-specific instruction templates
        if (artifact.templateSource) {
          stageInstructionTemplate(destPath, artifact.templateSource);
        }
        break;
    }

    written.push(artifact.label);
  }

  // Write manifest
  const manifest = buildManifest(artifacts, profile, scan);
  writeFileSync(
    join(stagingDir, MANIFEST_FILE),
    JSON.stringify(manifest, null, 2) + "\n",
    "utf8"
  );

  return { written, skipped };
}

function stageSkills(destDir) {
  if (!existsSync(SKILLS_DIR)) return;

  const skillDirs = readdirSync(SKILLS_DIR, { withFileTypes: true }).filter(
    (d) => d.isDirectory()
  );

  for (const dir of skillDirs) {
    const src = join(SKILLS_DIR, dir.name, "SKILL.md");
    if (existsSync(src)) {
      const dest = join(destDir, dir.name);
      mkdirSync(dest, { recursive: true });
      cpSync(src, join(dest, "SKILL.md"));
    }
  }
}

function stageInstructionTemplate(destPath, templateFile) {
  const src = join(INSTRUCTIONS_DIR, templateFile);
  if (existsSync(src)) {
    cpSync(src, destPath);
  }
}

// ─── Apply (move staged → final) ───────────────────────────────────────────

/**
 * Read the staging manifest and apply files.
 * @returns {{ applied: string[], skipped: string[], errors: string[] }}
 */
export function applyStaged(target, force = false) {
  const stagingDir = join(target, STAGING_DIR_NAME);
  const manifestPath = join(stagingDir, MANIFEST_FILE);

  if (!existsSync(stagingDir)) {
    return { applied: [], skipped: [], errors: ["No ai-setup/ directory found. Run onboard first."] };
  }

  // Read manifest
  let manifest = null;
  if (existsSync(manifestPath)) {
    try {
      manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
    } catch {}
  }

  if (!manifest) {
    return { applied: [], skipped: [], errors: ["No valid manifest found. Re-run onboard to regenerate."] };
  }

  const applied = [];
  const skipped = [];
  const errors = [];

  for (const artifact of manifest.artifacts) {
    const src = join(stagingDir, artifact.stagePath);
    const dest = join(target, artifact.targetPath);

    if (!existsSync(src)) {
      // For directory artifacts, check if directory exists
      if (artifact.id === "starter-skills") {
        const skillsSrc = join(stagingDir, ".github", "skills");
        if (existsSync(skillsSrc)) {
          const skillsDest = join(target, ".github", "skills");
          mkdirSync(skillsDest, { recursive: true });
          cpSync(skillsSrc, skillsDest, { recursive: true, force });
          applied.push(artifact.targetPath);
        }
      }
      continue;
    }

    if (existsSync(dest) && !force) {
      skipped.push(`${artifact.targetPath} (exists, use --force)`);
      continue;
    }

    try {
      mkdirSync(dirname(dest), { recursive: true });
      cpSync(src, dest);
      applied.push(artifact.targetPath);
    } catch (err) {
      errors.push(`${artifact.targetPath}: ${err.message}`);
    }
  }

  return { applied, skipped, errors };
}
